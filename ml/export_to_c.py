#!/usr/bin/env python3
"""export_to_c.py - Converts trained models/model.json into an optimized C++ header (model_data.h).

Generates a standalone, memory-efficient Edge AI inference engine for the ESP32:
- Deduplicates leaf probability vectors to minimize Flash storage (~35 KB total).
- Stores all tree nodes in Flash (PROGMEM) without using RAM.
- Includes feature normalization, gyro motion gating, and the 3-state accept/lock recognizer.
- Provides a built-in self-test (run_embedded_parity_test) to verify accuracy on boot.

Usage:
  python export_to_c.py
  (Outputs to firmware/glove_esp32/model_data.h)
"""

import json
import os
import sys

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
MODEL_JSON_PATH = os.path.join(BASE_DIR, "models", "model.json")
OUTPUT_HEADER_PATH = os.path.join(BASE_DIR, "..", "firmware", "glove_esp32", "model_data.h")

def export():
    if not os.path.exists(MODEL_JSON_PATH):
        print(f"Error: {MODEL_JSON_PATH} not found. Run train.py first.")
        sys.exit(1)

    with open(MODEL_JSON_PATH, "r") as f:
        model = json.load(f)

    classes = model["classes"]
    num_classes = len(classes)
    trees = model["trees"]
    num_trees = len(trees)
    test_vec = model.get("test_vector", {})

    # 1. Deduplicate unique leaf probability profiles
    unique_profiles = []
    profile_map = {}
    for t in trees:
        for val in t["value"]:
            if val:
                key = tuple(round(v, 4) for v in val)
                if key not in profile_map:
                    profile_map[key] = len(unique_profiles)
                    unique_profiles.append(key)

    num_profiles = len(unique_profiles)

    # 2. Flatten tree nodes with global index offsets
    tree_roots = []
    flattened_nodes = []
    
    for t in trees:
        tree_roots.append(len(flattened_nodes))
        offset = len(flattened_nodes)
        node_count = len(t["left"])
        
        for i in range(node_count):
            left = t["left"][i]
            right = t["right"][i]
            feat = t["feature"][i]
            thresh = t["threshold"][i]
            
            if left == -1:
                # Leaf node: right stores profile index
                prof_key = tuple(round(v, 4) for v in t["value"][i])
                prof_idx = profile_map[prof_key]
                flattened_nodes.append((-1, prof_idx, -1, 0.0))
            else:
                # Decision node: left and right point to global child node indices
                flattened_nodes.append((offset + left, offset + right, feat, thresh))

    total_nodes = len(flattened_nodes)

    # 3. Generate C++ Header
    lines = []
    lines.append("// model_data.h -- Auto-generated TinyML Random Forest for ESP32")
    lines.append("// Generated by ml/export_to_c.py. DO NOT EDIT DIRECTLY.")
    lines.append("")
    lines.append("#ifndef MODEL_DATA_H")
    lines.append("#define MODEL_DATA_H")
    lines.append("")
    lines.append("#include <Arduino.h>")
    lines.append("#include <math.h>")
    lines.append("")
    lines.append("// ===== Model Hyperparameters =====")
    lines.append(f"#define RF_NUM_CLASSES     {num_classes}")
    lines.append(f"#define RF_NUM_TREES       {num_trees}")
    lines.append(f"#define RF_NUM_FEATURES    {model.get('n_features', 8)}")
    lines.append(f"#define RF_TOTAL_NODES     {total_nodes}")
    lines.append(f"#define RF_NUM_PROFILES    {num_profiles}")
    lines.append(f"#define RF_WINDOW_SIZE     {model.get('window', 8)}")
    lines.append(f"#define RF_STEP_SIZE       {model.get('step', 2)}")
    lines.append(f"#define RF_MOTION_MAX      {float(model.get('motion_max', 60.0)):.1f}f")
    lines.append("#define RF_CONF_THRESHOLD  0.70f")
    lines.append("#define RF_STABLE_COUNT    4")
    lines.append("#define RF_NEUTRAL_UNLOCK  3")
    lines.append("")

    # Class and phrase arrays
    class_strs = ", ".join(f'"{c}"' for c in classes)
    lines.append(f"const char* const RF_CLASSES[RF_NUM_CLASSES] = {{{class_strs}}};")
    
    phrases = [model.get("phrases", {}).get(c, "") for c in classes]
    phrase_strs = ", ".join(f'"{p}"' for p in phrases)
    lines.append(f"const char* const RF_PHRASES[RF_NUM_CLASSES] = {{{phrase_strs}}};")

    categories = [model.get("category", {}).get(c, "Daily needs") if c != "neutral" else "" for c in classes]
    cat_strs = ", ".join(f'"{ct}"' for ct in categories)
    lines.append(f"const char* const RF_CATEGORIES[RF_NUM_CLASSES] = {{{cat_strs}}};")
    lines.append("")

    # Tree Node Struct
    lines.append("struct RFNode {")
    lines.append("  int16_t left;      // Left child node index, or -1 if leaf")
    lines.append("  int16_t right;     // Right child index, or profile index if left == -1")
    lines.append("  int8_t  feature;   // Feature index (0..7)")
    lines.append("  float   threshold; // Split value")
    lines.append("};")
    lines.append("")

    # Unique Leaf Probability Profiles (PROGMEM)
    lines.append(f"static const float RF_LEAF_PROFILES[{num_profiles}][{num_classes}] PROGMEM = {{")
    for prof in unique_profiles:
        vals = ", ".join(f"{v:.4f}f" for v in prof)
        lines.append(f"  {{{vals}}},")
    lines.append("};")
    lines.append("")

    # Tree Roots
    roots_str = ", ".join(str(r) for r in tree_roots)
    lines.append(f"static const uint16_t RF_TREE_ROOTS[{num_trees}] PROGMEM = {{{roots_str}}};")
    lines.append("")

    # Flattened Nodes Array (PROGMEM)
    lines.append(f"static const RFNode RF_NODES[{total_nodes}] PROGMEM = {{")
    for n in flattened_nodes:
        lines.append(f"  {{{n[0]}, {n[1]}, {n[2]}, {n[3]:.6f}f}},")
    lines.append("};")
    lines.append("")

    # Inference Functions
    lines.append("// ===== Inference Functions =====")
    lines.append("")
    lines.append("// Computes class probabilities across all 60 decision trees")
    lines.append("inline void rf_predict_proba(const float x[RF_NUM_FEATURES], float proba_out[RF_NUM_CLASSES]) {")
    lines.append("  for (int c = 0; c < RF_NUM_CLASSES; c++) proba_out[c] = 0.0f;")
    lines.append("  ")
    lines.append("  for (int t = 0; t < RF_NUM_TREES; t++) {")
    lines.append("    uint16_t curr = pgm_read_word(&RF_TREE_ROOTS[t]);")
    lines.append("    while (true) {")
    lines.append("      int16_t left = (int16_t)pgm_read_word(&RF_NODES[curr].left);")
    lines.append("      if (left == -1) {")
    lines.append("        // Leaf reached: right is profile index")
    lines.append("        int16_t prof_idx = (int16_t)pgm_read_word(&RF_NODES[curr].right);")
    lines.append("        for (int c = 0; c < RF_NUM_CLASSES; c++) {")
    lines.append("          proba_out[c] += pgm_read_float(&RF_LEAF_PROFILES[prof_idx][c]);")
    lines.append("        }")
    lines.append("        break;")
    lines.append("      }")
    lines.append("      int8_t feat = (int8_t)pgm_read_byte(&RF_NODES[curr].feature);")
    lines.append("      float thresh = pgm_read_float(&RF_NODES[curr].threshold);")
    lines.append("      int16_t right = (int16_t)pgm_read_word(&RF_NODES[curr].right);")
    lines.append("      curr = (x[feat] <= thresh) ? left : right;")
    lines.append("    }")
    lines.append("  }")
    lines.append("  ")
    lines.append("  const float inv_trees = 1.0f / (float)RF_NUM_TREES;")
    lines.append("  for (int c = 0; c < RF_NUM_CLASSES; c++) proba_out[c] *= inv_trees;")
    lines.append("}")
    lines.append("")

    # Feature Extractor
    lines.append("// Normalizes 5 flex sensor values and gravity vector into 8 features")
    lines.append("inline void rf_extract_features(")
    lines.append("    const float raw_win[RF_WINDOW_SIZE][11],")
    lines.append("    const float calib_open[5],")
    lines.append("    const float calib_fist[5],")
    lines.append("    float feat_out[8],")
    lines.append("    float* motion_out) {")
    lines.append("  ")
    lines.append("  // 1. Mean flex across window")
    lines.append("  float mean_flex[5] = {0};")
    lines.append("  float mean_acc[3]  = {0};")
    lines.append("  float sum_motion   = 0.0f;")
    lines.append("  ")
    lines.append("  for (int i = 0; i < RF_WINDOW_SIZE; i++) {")
    lines.append("    for (int k = 0; k < 5; k++) mean_flex[k] += raw_win[i][k];")
    lines.append("    for (int k = 0; k < 3; k++) mean_acc[k]  += raw_win[i][5 + k];")
    lines.append("    float gx = raw_win[i][8], gy = raw_win[i][9], gz = raw_win[i][10];")
    lines.append("    sum_motion += sqrtf(gx*gx + gy*gy + gz*gz);")
    lines.append("  }")
    lines.append("  ")
    lines.append("  const float inv_win = 1.0f / (float)RF_WINDOW_SIZE;")
    lines.append("  for (int k = 0; k < 5; k++) mean_flex[k] *= inv_win;")
    lines.append("  for (int k = 0; k < 3; k++) mean_acc[k]  *= inv_win;")
    lines.append("  *motion_out = sum_motion * inv_win;")
    lines.append("  ")
    lines.append("  // 2. Normalize flex (0.0=open, 1.0=fist)")
    lines.append("  for (int k = 0; k < 5; k++) {")
    lines.append("    float o = calib_open[k];")
    lines.append("    float f = calib_fist[k];")
    lines.append("    float span = f - o;")
    lines.append("    if (fabsf(span) < 30.0f) span = (span < 0) ? -30.0f : 30.0f;")
    lines.append("    float norm = (mean_flex[k] - o) / span;")
    lines.append("    if (norm < -0.2f) norm = -0.2f;")
    lines.append("    if (norm > 1.2f)  norm = 1.2f;")
    lines.append("    feat_out[k] = norm;")
    lines.append("  }")
    lines.append("  ")
    lines.append("  // 3. Gravity vector (clipped -1.5..1.5)")
    lines.append("  for (int k = 0; k < 3; k++) {")
    lines.append("    float a = mean_acc[k];")
    lines.append("    if (a < -1.5f) a = -1.5f;")
    lines.append("    if (a > 1.5f)  a = 1.5f;")
    lines.append("    feat_out[5 + k] = a;")
    lines.append("  }")
    lines.append("}")
    lines.append("")

    # Recognizer Class
    lines.append("// ===== 3-State Accept/Lock Recognizer (Armed -> Candidate -> Locked) =====")
    lines.append("class EdgeRecognizer {")
    lines.append("public:")
    lines.append("  int cand;")
    lines.append("  int count;")
    lines.append("  bool locked;")
    lines.append("  int neutral;")
    lines.append("  ")
    lines.append("  EdgeRecognizer() : cand(-1), count(0), locked(false), neutral(0) {}")
    lines.append("  ")
    lines.append("  // Evaluates one window. Returns class index (1..9) when phrase fires, else -1.")
    lines.append("  int update(const float proba[RF_NUM_CLASSES], bool moving) {")
    lines.append("    int best_k = 0;")
    lines.append("    float best_p = proba[0];")
    lines.append("    for (int i = 1; i < RF_NUM_CLASSES; i++) {")
    lines.append("      if (proba[i] > best_p) {")
    lines.append("        best_p = proba[i];")
    lines.append("        best_k = i;")
    lines.append("      }")
    lines.append("    }")
    lines.append("    ")
    lines.append("    bool is_neutral = (best_k == 0); // Class 0 is neutral")
    lines.append("    ")
    lines.append("    if (moving) {")
    lines.append("      cand = -1; count = 0; neutral = 0;")
    lines.append("      return -1;")
    lines.append("    }")
    lines.append("    ")
    lines.append("    if (locked) {")
    lines.append("      neutral = (is_neutral && best_p >= 0.60f) ? (neutral + 1) : 0;")
    lines.append("      if (neutral >= RF_NEUTRAL_UNLOCK) {")
    lines.append("        locked = false; neutral = 0; cand = -1; count = 0;")
    lines.append("      }")
    lines.append("      return -1;")
    lines.append("    }")
    lines.append("    ")
    lines.append("    if (is_neutral || best_p < RF_CONF_THRESHOLD) {")
    lines.append("      cand = -1; count = 0;")
    lines.append("      return -1;")
    lines.append("    }")
    lines.append("    ")
    lines.append("    if (best_k == cand) {")
    lines.append("      count++;")
    lines.append("    } else {")
    lines.append("      cand = best_k; count = 1;")
    lines.append("    }")
    lines.append("    ")
    lines.append("    if (count >= RF_STABLE_COUNT) {")
    lines.append("      locked = true; neutral = 0; cand = -1; count = 0;")
    lines.append("      return best_k;")
    lines.append("    }")
    lines.append("    return -1;")
    lines.append("  }")
    lines.append("};")
    lines.append("")

    # Test Vector Parity Check
    if "features" in test_vec and "proba" in test_vec:
        tv_feat = ", ".join(f"{v:.6f}f" for v in test_vec["features"])
        tv_proba = ", ".join(f"{v:.6f}f" for v in test_vec["proba"])
        lines.append("// Built-in self-test verifying mathematical parity with scikit-learn")
        lines.append(f"static const float RF_TEST_FEAT[8] PROGMEM = {{{tv_feat}}};")
        lines.append(f"static const float RF_TEST_PROBA[10] PROGMEM = {{{tv_proba}}};")
        lines.append("")
        lines.append("inline bool run_embedded_parity_test() {")
        lines.append("  float tf[8];")
        lines.append("  for (int i = 0; i < 8; i++) tf[i] = pgm_read_float(&RF_TEST_FEAT[i]);")
        lines.append("  float proba[10];")
        lines.append("  rf_predict_proba(tf, proba);")
        lines.append("  for (int c = 0; c < 10; c++) {")
        lines.append("    float expected = pgm_read_float(&RF_TEST_PROBA[c]);")
        lines.append("    if (fabsf(proba[c] - expected) > 0.005f) return false;")
        lines.append("  }")
        lines.append("  return true;")
        lines.append("}")
        lines.append("")

    lines.append("#endif // MODEL_DATA_H")

    content = "\n".join(lines) + "\n"
    
    os.makedirs(os.path.dirname(os.path.abspath(OUTPUT_HEADER_PATH)), exist_ok=True)
    with open(OUTPUT_HEADER_PATH, "w") as f:
        f.write(content)
        
    kb_size = len(content) / 1024
    print(f"Export successful!")
    print(f" - Header saved to: {OUTPUT_HEADER_PATH}")
    print(f" - Total trees: {num_trees}")
    print(f" - Total nodes: {total_nodes}")
    print(f" - Unique profiles: {num_profiles}")
    print(f" - Header size: {kb_size:.1f} KB")

if __name__ == "__main__":
    export()
